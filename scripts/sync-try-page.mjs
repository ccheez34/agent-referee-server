// Builds src/try-page.ts from web/try.html, the browser page served at GET /try (made by the web client's author).
// Run after updating web/try.html:  node scripts/sync-try-page.mjs [path-to-new-index.html]
// It copies the given page into web/try.html (if a path is given), then writes the page as a string plus the SHA-256
// of each inline <script>, which the Content-Security-Policy on /try allows by hash.
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";

const src = new URL("../web/try.html", import.meta.url);
if (process.argv[2]) await writeFile(src, await readFile(process.argv[2]));
const html = await readFile(src, "utf8");
const hashes = [...html.matchAll(/<script\b(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map((m) => "sha256-" + createHash("sha256").update(m[1], "utf8").digest("base64"));
if (!hashes.length) throw new Error("web/try.html has no inline script: is it the right file?");
const out = `// Generated by scripts/sync-try-page.mjs from web/try.html. Don't edit by hand.
export const TRY_HTML = ${JSON.stringify(html)};
export const TRY_SCRIPT_HASHES = ${JSON.stringify(hashes)};
`;
await writeFile(new URL("../src/try-page.ts", import.meta.url), out);
console.log(`src/try-page.ts: ${html.length} characters, ${hashes.length} inline script(s).`);
